#!/bin/bash
# ============================================================================
# install-lib.sh - Shared library for BillionMail split installer
# ----------------------------------------------------------------------------
# Source this file from other install-*.sh scripts:
#   SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
#   source "${SCRIPT_DIR}/install-lib.sh"
#
# Provides:
#   - Constants (container names, ports, paths)
#   - Helper functions (logging, OS detection, port checks, etc.)
# ============================================================================

# ---- Paths & state --------------------------------------------------------
LIB_SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
STATE_FILE="${LIB_SCRIPT_DIR}/install-state.env"
DBPASS_FILE="${LIB_SCRIPT_DIR}/DBPASS_file.pl"
CONF_FILE="${LIB_SCRIPT_DIR}/billionmail.conf"
ENV_FILE="${LIB_SCRIPT_DIR}/.env"
SSL_DIR="${LIB_SCRIPT_DIR}/ssl-self-signed"
BACKUP_DIR="${LIB_SCRIPT_DIR}/backup"

# ---- Container names ------------------------------------------------------
CONTAINER_PROJECT_NAME="${CONTAINER_PROJECT_NAME:-billionmail}"
PGSQL_CONTAINER_NAME="${CONTAINER_PROJECT_NAME}-pgsql-billionmail-1"
DOVECOT_CONTAINER_NAME="${CONTAINER_PROJECT_NAME}-dovecot-billionmail-1"
POSTFIX_CONTAINER_NAME="${CONTAINER_PROJECT_NAME}-postfix-billionmail-1"
RSPAMD_CONTAINER_NAME="${CONTAINER_PROJECT_NAME}-rspamd-billionmail-1"

# ---- Mail ports -----------------------------------------------------------
SMTP_PORT="${SMTP_PORT:-25}"
SMTPS_PORT="${SMTPS_PORT:-465}"
SUBMISSION_PORT="${SUBMISSION_PORT:-587}"
IMAP_PORT="${IMAP_PORT:-143}"
IMAPS_PORT="${IMAPS_PORT:-993}"
POP_PORT="${POP_PORT:-110}"
POPS_PORT="${POPS_PORT:-995}"

# ---- Internal & web ports -------------------------------------------------
REDIS_PORT="${REDIS_PORT:-127.0.0.1:26379}"
SQL_PORT="${SQL_PORT:-127.0.0.1:25432}"
HTTP_PORT="${HTTP_PORT:-80}"
HTTPS_PORT="${HTTPS_PORT:-443}"

# ---- OS / arch ------------------------------------------------------------
SUPPORTED_ARCHS=("x86_64" "aarch64")
CPU_architecture="$(uname -m)"
DOWNLOAD_URL="${DOWNLOAD_URL:-https://node.aapanel.com}"

# ---- Misc -----------------------------------------------------------------
create_time="$(date +%s)"
time="$(date +%Y_%m_%d_%H_%M_%S)"

# ============================================================================
# Logging helpers
# ============================================================================
log_info()  { echo -e "\033[1;32m[INFO]\033[0m  $*"; }
log_warn()  { echo -e "\033[1;33m[WARN]\033[0m  $*"; }
log_error() { echo -e "\033[1;31m[ERROR]\033[0m $*" >&2; }
log_step()  { echo -e "\n\033[1;36m==>\033[0m \033[1m$*\033[0m"; }

GetSysInfo() {
    if [ -s "/etc/redhat-release" ]; then
        SYS_VERSION=$(cat /etc/redhat-release)
    elif [ -s "/etc/issue" ]; then
        SYS_VERSION=$(cat /etc/issue)
    fi
    SYS_INFO=$(uname -a)
    SYS_BIT=$(getconf LONG_BIT 2>/dev/null || echo "?")
    MEM_TOTAL=$(free -m 2>/dev/null | grep Mem | awk '{print $2}')
    CPU_INFO=$(getconf _NPROCESSORS_ONLN 2>/dev/null || echo "?")

    echo -e "${SYS_VERSION:-unknown}"
    echo -e "Bit:${SYS_BIT} Mem:${MEM_TOTAL:-?}M Core:${CPU_INFO}"
    echo -e "${SYS_INFO}"
    echo -e "Please screenshot the above error message and post to https://github.com/aaPanel/BillionMail/issues for help"
}

Red_Error() {
    echo '================================================='
    printf '\033[1;31;40m%b\033[0m\n' "$@"
    GetSysInfo
    exit 1
}

Command_Exists() { command -v "$@" >/dev/null 2>&1; }

Is_Darwin() {
    case "$(uname -s)" in
        *darwin*) true ;;
        *Darwin*) true ;;
        *)        false ;;
    esac
}

# ============================================================================
# State load/save — share variables between scripts
# ============================================================================
save_state() {
    cat > "${STATE_FILE}" <<EOF
# Generated by 01-env-prepare.sh — do not edit manually
BILLIONMAIL_HOSTNAME='${BILLIONMAIL_HOSTNAME}'
ADD_MAIL_BILLIONMAIL_HOSTNAME='${ADD_MAIL_BILLIONMAIL_HOSTNAME}'
BILLIONMAIL_TIME_ZONE='${BILLIONMAIL_TIME_ZONE}'
SafePath='${SafePath}'
REDISPASS='${REDISPASS}'
ADMIN_USERNAME='${ADMIN_USERNAME}'
ADMIN_PASSWORD='${ADMIN_PASSWORD}'
DBPASS='${DBPASS}'
SMTP_PORT='${SMTP_PORT}'
SMTPS_PORT='${SMTPS_PORT}'
SUBMISSION_PORT='${SUBMISSION_PORT}'
IMAP_PORT='${IMAP_PORT}'
IMAPS_PORT='${IMAPS_PORT}'
POP_PORT='${POP_PORT}'
POPS_PORT='${POPS_PORT}'
create_time='${create_time}'
EOF
    chmod 600 "${STATE_FILE}"
    log_info "State saved → ${STATE_FILE}"
}

load_state() {
    if [ ! -s "${STATE_FILE}" ]; then
        Red_Error "State file missing: ${STATE_FILE}" \
                  "Please run 01-env-prepare.sh first."
    fi
    # shellcheck disable=SC1090
    source "${STATE_FILE}"
    log_info "State loaded ← ${STATE_FILE}"
}

# ============================================================================
# Pre-flight checks
# ============================================================================
check_root() {
    if [ "$(whoami)" != "root" ]; then
        Red_Error "Non-root install. Please run as root: sudo bash $0 $*"
    fi
}

check_arch() {
    if [[ ! " ${SUPPORTED_ARCHS[@]} " =~ " ${CPU_architecture} " ]]; then
        Red_Error "Sorry, architecture '${CPU_architecture}' is not supported." \
                  "Please use x86_64 or aarch64."
    fi
    local is64bit
    is64bit=$(getconf LONG_BIT)
    if [ "${is64bit}" != '64' ]; then
        Red_Error "BillionMail does not support 32-bit systems."
    fi
}

LXC_install_tips() {
    if ! Command_Exists hostnamectl; then
        return 0
    fi
    local System_Info check_container
    System_Info=$(hostnamectl 2>/dev/null || true)
    check_container=$(echo "${System_Info}" | grep "Chassis" | awk -F":" '{print $2}')
    if [[ "${check_container}" =~ "container" ]]; then
        log_warn "Installing in an LXC container. May not install properly."
        log_warn "Docker may not be able to correctly obtain the number of CPU cores."
        log_warn "Recommended: VPS or physical machine."
        log_warn "Must be turned on 'Unprivileged container' + 'nesting'."
        local lxc=""
        while [ "${lxc}" != 'y' ] && [ "${lxc}" != 'n' ]; do
            read -p "Continue install in LXC container? (y/n): " lxc
        done
        [ "${lxc}" == 'n' ] && { echo "Install canceled."; exit 1; }
    fi
}

# ============================================================================
# Package manager
# ============================================================================
Get_Pack_Manager() {
    if [ -f "/usr/bin/yum" ] && [ -d "/etc/yum.repos.d" ]; then
        PM="yum"
    elif [ -f "/usr/bin/apt-get" ] && [ -f "/usr/bin/dpkg" ]; then
        PM="apt-get"
    else
        PM=""
    fi
    echo "${PM}"
}

Install_RPM_Pack() {
    local yumPacks="wget curl tar gzip git firewalld ca-certificates"
    yum install -y ${yumPacks}
    for yumPack in ${yumPacks}; do
        local rpmPack packCheck
        rpmPack=$(rpm -q "${yumPack}" 2>/dev/null || echo "not installed")
        packCheck=$(echo "${rpmPack}" | grep not)
        if [ "${packCheck}" ]; then
            yum install "${yumPack}" -y
        fi
    done
    setenforce 0 2>/dev/null || true
    sed -i 's/SELINUX=enforcing/SELINUX=disabled/' /etc/selinux/config 2>/dev/null || true
}

Install_Deb_Pack() {
    local debPacks="wget curl tar gzip git lsb-release ufw ca-certificates"
    apt-get update -y
    DEBIAN_FRONTEND=noninteractive apt-get install -y ${debPacks} \
        --allow-downgrades --allow-remove-essential --allow-change-held-packages
    for debPack in ${debPacks}; do
        if ! dpkg -l "${debPack}" >/dev/null 2>&1; then
            apt-get install -y "${debPack}"
        fi
    done
}

# ============================================================================
# Port checking
# ============================================================================
PORT() {
    local command_port=""
    if Command_Exists ss; then
        command_port="ss"
    elif Command_Exists netstat; then
        command_port="netstat"
    else
        log_warn "Neither 'ss' nor 'netstat' found. Cannot check ports."
        return 0
    fi

    local check_command
    check_command=$(${command_port} -ltnp 2>/dev/null | \
        grep -E ":(${SMTP_PORT}|${SMTPS_PORT}|${SUBMISSION_PORT}|${POP_PORT}|${IMAP_PORT}|${IMAPS_PORT}|${POPS_PORT})\s")
    if [[ -n "${check_command}" ]]; then
        echo "Checking the port is used:"
        echo "${check_command}" | grep -v "docker-proxy"
        log_warn "BillionMail needs ports ${SMTP_PORT}|${SMTPS_PORT}|${SUBMISSION_PORT}|${POP_PORT}|${IMAP_PORT}|${IMAPS_PORT}|${POPS_PORT}."
    fi
}

Check_Port() { PORT; }

# ============================================================================
# Distribution detection
# ============================================================================
Get_Distribution() {
    local lsb_dist="" lsb_name=""
    if [ -r /etc/os-release ]; then
        lsb_dist="$(. /etc/os-release && echo "$ID")"
        lsb_name="$(. /etc/os-release && echo "$NAME")"
    fi
    echo "${lsb_dist} ${lsb_name}"
}

Check_Forked() {
    if Command_Exists lsb_release; then
        set +e
        lsb_release -a -u >/dev/null 2>&1
        local lsb_release_exit_code=$?
        set -e
        if [ "${lsb_release_exit_code}" = "0" ]; then
            lsb_dist=$(lsb_release -a -u 2>&1 | tr '[:upper:]' '[:lower:]' | \
                grep -E 'id' | cut -d ':' -f 2 | tr -d '[:space:]')
            dist_version=$(lsb_release -a -u 2>&1 | tr '[:upper:]' '[:lower:]' | \
                grep -E 'codename' | cut -d ':' -f 2 | tr -d '[:space:]')
        fi
    fi
}

# ============================================================================
# Animated wait
# ============================================================================
Bored_waiting() {
    local w_time="$1"
    local msg="${2:-Please wait}"
    local progress="."
    local i
    for ((i = 0; i < w_time; i++)); do
        printf "%s %-10s %d\r" "${msg}" "${progress}" "$((i + 1))"
        sleep 1
        if [ "${progress}" == ".........." ]; then
            progress="."
        else
            progress+="."
        fi
    done
    printf "%s %-10s %d\n" "${msg}" ".........." "${w_time}"
}

# ============================================================================
# Docker detection
# ============================================================================
Docker_Check() {
    is_docker="0"
    if Command_Exists docker; then
        is_docker="1"
    fi
    echo "docker installed: ${is_docker}"
}

Docker_Compose_Check() {
    is_docker_compose="0"
    if Command_Exists docker-compose; then
        is_docker_compose="1"
        DOCKER_COMPOSE="docker-compose"
    else
        if Command_Exists docker; then
            if docker compose version >/dev/null 2>&1; then
                is_docker_compose="1"
                DOCKER_COMPOSE="docker compose"
            fi
        fi
    fi
}

# ============================================================================
# Distribution fallback for the docker yum repo
# ============================================================================
create_docker_yum_repo() {
    cat <<EOF >/etc/yum.repos.d/docker-ce.repo
[docker-ce-stable]
name=Docker CE Stable - \$basearch
baseurl=https://download.docker.com/linux/centos/\$releasever/\$basearch/stable
enabled=1
gpgcheck=1
gpgkey=https://download.docker.com/linux/centos/gpg
EOF
}
